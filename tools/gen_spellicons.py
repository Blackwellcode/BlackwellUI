"""Generate BlackwellUI's SpellIcons.lua from the client's own game data.

Usage: python -I gen_spellicons.py <patch.MPQ> <out SpellIcons.lua>

Source: DBFilesClient\\Spell.dbc (col 0 id, 117 icon id, 120 enUS name) and
DBFilesClient\\SpellIcon.dbc (col 0 id, 1 texture path). Columns verified on
this client with Fireball (133 -> Spell_Fire_FlameBolt) and Frostbolt
(116 -> Spell_Frost_FrostBolt02). For every spell name the icon of its
lowest spell id with a real icon is kept.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mpq import MPQ  # noqa: E402

COL_ID, COL_ICON, COL_NAME = 0, 117, 120
SKIP_ICONS = {"temp", ""}


def parse_dbc(raw):
    magic, nrec, nfield, rsize, ssize = struct.unpack("<4sIIII", raw[:20])
    if magic != b"WDBC":
        raise ValueError("not a WDBC file")
    recs = [struct.unpack("<%dI" % nfield, raw[20 + i * rsize: 20 + i * rsize + nfield * 4]) for i in range(nrec)]
    strings = raw[20 + nrec * rsize: 20 + nrec * rsize + ssize]
    return recs, strings


def cstr(strings, off):
    end = strings.find(b"\0", off)
    return strings[off:end]


def lua_str(b):
    out = b.replace(b"\\", b"\\\\").replace(b'"', b'\\"').replace(b"\n", b"\\n").replace(b"\r", b"\\r")
    return b'"' + out + b'"'


def main():
    mpq_path, out_path = sys.argv[1], sys.argv[2]
    m = MPQ(mpq_path)
    spells, sstr = parse_dbc(m.read("DBFilesClient\\Spell.dbc"))
    icons, istr = parse_dbc(m.read("DBFilesClient\\SpellIcon.dbc"))

    icon_file = {}
    for r in icons:
        path = cstr(istr, r[1]).decode("latin-1")
        base = path.replace("/", "\\").split("\\")[-1]
        if base.lower() not in SKIP_ICONS:
            icon_file[r[0]] = base

    chosen = {}
    for r in sorted(spells, key=lambda x: x[COL_ID]):
        name = cstr(sstr, r[COL_NAME]) if r[COL_NAME] < len(sstr) else b""
        if not name.strip() or name in chosen:
            continue
        base = icon_file.get(r[COL_ICON])
        if base:
            chosen[name] = base

    files = sorted(set(chosen.values()), key=str.lower)
    index = {f: i + 1 for i, f in enumerate(files)}

    lines = [
        b"-------------------------------------------------------------------------------",
        b"--  BlackwellUI for Azeroth Survivors  -  SpellIcons.lua",
        b"--  Copyright (c) 2026 Pierre (Blackwellcode). All rights reserved. See LICENSE.",
        b"--  Spell name -> icon lookup, generated by BlackwellUI's own build tool from",
        b"--  this client's game data (DBFilesClient\\Spell.dbc + SpellIcon.dbc).",
        b"--  Each icon file is listed once; names point at it by index. Do not edit by",
        b"--  hand: regenerate with the tool after a client update.",
        b"-------------------------------------------------------------------------------",
        b"",
        b"local B = BlackwellUI",
        b"",
        b"B.SPELL_ICON_FILES = {",
    ]
    for f in files:
        lines.append(b"    " + lua_str(f.encode("latin-1")) + b",")
    lines.append(b"}")
    lines.append(b"")
    lines.append(b"B.SPELL_ICON_INDEX = {")
    for name in sorted(chosen, key=lambda n: n.lower()):
        lines.append(b"    [" + lua_str(name) + b"] = " + str(index[chosen[name]]).encode() + b",")
    lines.append(b"}")
    lines.append(b"")
    with open(out_path, "wb") as fh:
        fh.write(b"\n".join(lines) + b"\n")
    print("spells", len(spells), "names", len(chosen), "icon files", len(files),
          "->", out_path, os.path.getsize(out_path), "bytes")


if __name__ == "__main__":
    main()
