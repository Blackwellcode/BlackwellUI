"""Generate BlackwellUI's GameStrings.lua from the game's own locale data.

Usage: python -I gen_gamestrings.py <AzerothSurvivors.exe> <out GameStrings.lua>

The game writes its spell tooltips in the game language. Build.lua reads
those tooltips back (cast line, crit line, "Talents: " sections, damage
school), so it needs the game's own wording of each marker in every
language. Row: English text first, then one entry per language code that
differs from English. Templates keep the game's {name} placeholders.
"""
import sys

from gen_abilitynames import LANG_ORDER, extract_blocks, lua_str

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

# BlackwellUI id -> game locale key
STRINGS = [
    ("automatic", "Automatic"),
    ("passive", "Passive"),
    ("talents", "Talents: "),
    ("upgrades", "Upgrades: "),
    ("bonuses", "Your bonuses: "),
    ("crit", "{p}% chance to crit for {crit}% damage"),
    ("cooldown", "common.cooldown_sec"),
    ("damage", "{dmg} {school} damage"),
    ("rank", "Rank {n}"),
    ("yards", "common.yards"),
    ("list_sep", "common.list_sep"),
    ("school_Physical", "Physical"),
    ("school_Holy", "Holy"),
    ("school_Fire", "Fire"),
    ("school_Nature", "Nature"),
    ("school_Frost", "Frost"),
    ("school_Shadow", "Shadow"),
    ("school_Arcane", "Arcane"),
]


def main():
    exe_path, out_path = sys.argv[1], sys.argv[2]
    with open(exe_path, "rb") as fh:
        exe = fh.read()
    blocks = extract_blocks(exe)
    missing = [c for c in ["en"] + LANG_ORDER if c not in blocks]
    if missing:
        raise SystemExit("missing languages: %s" % missing)
    en = blocks["en"]
    lines = [
        "-------------------------------------------------------------------------------",
        "--  BlackwellUI for Azeroth Survivors  -  GameStrings.lua",
        "--  Copyright (c) 2026 Pierre (Blackwellcode). All rights reserved. See LICENSE.",
        "--  The game's own tooltip wording per game language, generated by",
        "--  BlackwellUI's own build tool from the game's built-in language data, so",
        "--  spell tooltips can be read in any game language. The texts belong to",
        "--  the game; see THIRD-PARTY-NOTICES.md. Row: English first, then one",
        "--  entry per language code. Do not edit by hand.",
        "-------------------------------------------------------------------------------",
        "",
        "local B = BlackwellUI",
        "",
        "B.GAME_STRINGS = {",
    ]
    for sid, key in STRINGS:
        if key not in en:
            raise SystemExit("game key not found: %r" % key)
        parts = [lua_str(en[key])]
        for code in LANG_ORDER:
            v = blocks[code].get(key)
            if v is None:
                raise SystemExit("%s missing in %s" % (key, code))
            if v != en[key]:
                parts.append("%s = %s" % (code, lua_str(v)))
        lines.append("    %s = { %s }," % (sid, ", ".join(parts)))
    lines.append("}")
    lines.append("")
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("strings", len(STRINGS), "->", out_path)


if __name__ == "__main__":
    main()
