"""Generate BlackwellUI's AbilityNames.lua from the game's own locale data.

Usage: python -I gen_abilitynames.py <AzerothSurvivors.exe> <out AbilityNames.lua>

The exe embeds one JSON object per game language ("<code><Name>{ ... }").
Every "ability.<key>.name" entry becomes one row: the English name first,
then the translation per language code. The <key> is the same id the game
reports in AZS_SPELLS[i].key.
"""
import json
import re
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
LANG_ORDER = ["de", "fr", "es", "pt", "pl", "cs", "ro", "tr", "ru", "uk", "zh", "ja", "ko"]


def extract_blocks(exe):
    dec = json.JSONDecoder()
    blocks = {}
    for m in re.finditer(rb'\{\s*\n\s*"game\.title"', exe):
        st = m.start()
        head = exe[max(0, st - 40):st]
        hm = re.search(rb"([a-z]{2})([^\x00-\x1f{}]{2,30})$", head)
        text = exe[st:st + 4_000_000].decode("utf-8", "replace")
        obj, _ = dec.raw_decode(text)
        code = hm.group(1).decode() if hm else "?"
        # The English block's label is "English" with no code in front of it,
        # so the 2-letter grab lands inside the word ("ng").
        if head.endswith(b"English"):
            code = "en"
        blocks[code] = obj
    return blocks


def lua_str(s):
    b = s.encode("utf-8")
    b = b.replace(b"\\", b"\\\\").replace(b'"', b'\\"').replace(b"\n", b"\\n").replace(b"\r", b"")
    return '"' + b.decode("utf-8") + '"'


def main():
    exe_path, out_path = sys.argv[1], sys.argv[2]
    with open(exe_path, "rb") as fh:
        exe = fh.read()
    blocks = extract_blocks(exe)
    if "en" not in blocks:
        raise SystemExit("English block not found")
    missing = [c for c in LANG_ORDER if c not in blocks]
    if missing:
        raise SystemExit("missing languages: %s" % missing)
    en = blocks["en"]
    keys = sorted(k for k in en if re.fullmatch(r"ability\.[a-z0-9_]+\.name", k))
    lines = [
        "-------------------------------------------------------------------------------",
        "--  BlackwellUI for Azeroth Survivors  -  AbilityNames.lua",
        "--  Copyright (c) 2026 Pierre (Blackwellcode). All rights reserved. See LICENSE.",
        "--  Ability names per game language, generated by BlackwellUI's own build tool",
        "--  from the game's built-in language data (ability.<key>.name). The names",
        "--  themselves belong to the game; see THIRD-PARTY-NOTICES.md. Row: English",
        "--  name first, then one entry per language code. Do not edit by hand.",
        "-------------------------------------------------------------------------------",
        "",
        "local B = BlackwellUI",
        "",
        "B.ABILITY_NAMES = {",
    ]
    count = 0
    for k in keys:
        aid = k.split(".")[1]
        parts = [lua_str(en[k])]
        for code in LANG_ORDER:
            v = blocks[code].get(k)
            if v and v != en[k]:
                parts.append("%s = %s" % (code, lua_str(v)))
        lines.append("    %s = { %s }," % (aid, ", ".join(parts)))
        count += 1
    lines.append("}")
    lines.append("")
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("languages", sorted(blocks), "abilities", count, "->", out_path)


if __name__ == "__main__":
    main()
